import { describe, expect, it } from 'vitest';
import tool from './dockerignore-generator.tool';

type Result = { output: string; render?: string; stats?: Record<string, number>; notes?: string[] };
const run = async (text: string, options: Record<string, string | number | boolean> = {}) =>
  (await tool.run({ text, options })) as Result;
const out = (o: Record<string, string | number | boolean> = {}) => run('', o).then((r) => r.output);

describe('dockerignore-generator', () => {
  it('includes node preset patterns', async () => {
    const o = await out({ preset: 'node' });
    expect(o).toContain('node_modules');
    expect(o).toContain('dist');
    expect(o).toContain('.git');
    expect(o).toContain('Dockerfile*');
  });

  it('omits dotfiles when includeHidden=false', async () => {
    const o = await out({ preset: 'node', includeHidden: false });
    expect(o).not.toContain('.git');
    expect(o).not.toContain('.vscode');
    expect(o).toContain('node_modules');
  });

  it('appends custom patterns and counts them', async () => {
    const r = await run('', { preset: 'generic', extra: 'build/\ncoverage/' });
    expect(r.output).toContain('build/');
    expect(r.output).toContain('coverage/');
    expect(r.stats).toEqual(expect.objectContaining({ customLines: 2 }));
    expect(r.stats!.patterns).toBeGreaterThanOrEqual(5);
  });

  it('respects sectionComments=false', async () => {
    const o = await out({ preset: 'node', sectionComments: false });
    expect(o).not.toContain('# Version control / CI');
    expect(o).toContain('node_modules');
    expect(o).toContain('# generated by');
  });

  it('never emits empty section separators at the end', async () => {
    const o = await out({ preset: 'generic' });
    expect(o.trim().endsWith('/**')).toBe(false);
    expect(o.trim()).not.toBe('');
    expect(o).toContain('dist');
  });
});
