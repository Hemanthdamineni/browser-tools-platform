function lines(value: unknown): string[] {
  return String(value ?? '')
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l !== '');
}

async function run(input: TextRunInput): Promise<TextRunResult> {
  const o = resolveOptions(meta, input.options);
  const preset = PRESETS[String(o.preset ?? 'node')] ?? PRESETS['node']!;
  const includeHidden = o.includeHidden !== false;
  const sectionComments = o.sectionComments !== false;
  const extra = lines(o.extra ?? '');

  const out: string[] = [];
  out.push('# .dockerignore — keep the build context small and fast');
  out.push('# generated by .dockerignore Generator');
  out.push('');
  let count = 0;
  for (const section of preset.patterns) {
    let items = section.items;
    if (!includeHidden) {
      items = items.filter((i) => !i.startsWith('.'));
    }
    if (sectionComments) {
      out.push('# ' + section.section);
    }
    for (const item of items) {
      out.push(item);
      count += 1;
    }
    out.push('');
  }
  if (extra.length > 0) {
    if (sectionComments) out.push('# Custom');
    out.push(...extra);
    count += extra.length;
    out.push('');
  }

  const text = out.join('\n') + '\n';

  return {
    output: text,
    render: 'text',
    language: 'text',
    stats: { patterns: count, presetLines: count - extra.length, customLines: extra.length },
    notes: [
      'Preset: ' + preset.name + ' (' + (count - extra.length) + ' patterns).',
      'Add your own patterns under Custom or in the input to fine-tune context size.',
    ],
  };
}

const tool: TextToolModule = { meta, run };
export default tool;
