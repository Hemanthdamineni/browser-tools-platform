/** Uniform integer in [0, max) from the CSPRNG, using rejection sampling (no modulo bias). */
export function randomInt(max: number): number {
  if (!Number.isInteger(max) || max <= 0) throw new ToolError('Invalid random range.');
  if (max === 1) return 0;
  const limit = Math.floor(0x1_0000_0000 / max) * max;
  const buf = new Uint32Array(1);
  for (;;) {
    crypto.getRandomValues(buf);
    const v = buf[0]!;
    if (v < limit) return v % max;
  }
}

const SEPARATORS: Record<string, string> = {
  hyphen: '-',
  space: ' ',
  dot: '.',
  underscore: '_',
  none: '',
};

function run(input: TextRunInput): TextRunResult {
  const o = resolveOptions(meta, input.options);

  const rawWords = Math.floor(Number(o.words));
  if (!Number.isFinite(rawWords)) throw new ToolError('Word count must be a number.');
  const wordCount = Math.min(12, Math.max(3, rawWords));

  const sep = SEPARATORS[String(o.separator)] ?? '-';
  const capitalize = Boolean(o.capitalize);
  const addNumber = Boolean(o.addNumber);

  const parts: string[] = [];
  for (let i = 0; i < wordCount; i++) {
    let w = WORDS[randomInt(WORDS.length)]!;
    if (capitalize) w = w.charAt(0).toUpperCase() + w.slice(1);
    parts.push(w);
  }
  if (addNumber) parts.push(String(randomInt(1000)));

  const bits = Math.log2(WORDS.length) * wordCount;

  return {
    output: parts.join(sep),
    render: 'code',
    filename: 'passphrase.txt',
    stats: {
      'wordlist size': WORDS.length,
      words: wordCount,
      'entropy (bits)': Math.round(bits),
      'bits per word': Math.log2(WORDS.length).toFixed(2),
    },
  };
}

const tool: TextToolModule = { meta, run };
export default tool;
